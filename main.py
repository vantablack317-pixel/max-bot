import os
import time
import requests

# Берем токен из настроек Bothost (переменная окружения)
TOKEN = os.environ.get('BOT_TOKEN')
API_URL = 'https://platform-api2.max.ru'
HEADERS = {'Authorization': TOKEN}

# ТВОЯ ССЫЛКА ИЗ ЛИЧНОГО КАБИНЕТА (Вставь свою!)
PARTNER_LINK = "YOUR_PARTNER_LINK_HERE" 

def send_message(chat_id, text):
    """Функция для отправки сообщения в MAX"""
    requests.post(
        f'{API_URL}/messages',
        headers=HEADERS,
        params={'chat_id': chat_id},
        json={'text': text}
    )

def main():
    print("Бот запущен и ждет сообщений...")
    marker = None
    
    while True:
        try:
            # Получаем новые сообщения (Long Polling)
            params = {'timeout': 30}
            if marker:
                params['marker'] = marker
                
            response = requests.get(f'{API_URL}/updates', headers=HEADERS, params=params)
            data = response.json()
            
            if 'updates' in data:
                for update in data['updates']:
                    marker = update.get('marker', marker)
                    
                    if update.get('update_type') == 'message_created':
                        message = update['message']
                        chat_id = message['chat_id']
                        text = message['body'].get('text', '').lower().strip()
                        
                        # --- НАЧАЛО СКРИПТА ОТВЕТОВ ---
                        
                        # 1. Приветствие и Старт
                        if text in ['/start', 'привет', 'здравствуйте', 'добрый день', 'добрый вечер', 'хай', 'ку']:
                            send_message(chat_id, 'Привет! 👋 Я бот-помощник по вакансиям курьера-партнера в Яндекс Еду.\n\nЗдесь можно узнать условия, график и получить официальную ссылку на регистрацию.\n\nНапиши интересующий вопрос (например: "сколько платят", "какие документы", "как начать") или введи /link, чтобы сразу получить ссылку.')
                        
                        # 2. Выдача ссылки и Начало работы
                        elif any(word in text for word in ['/link', 'ссылка', 'регистрация', 'как начать', 'хочу работать', 'куда нажать', 'анкета', 'устроиться', 'подключиться']):
                            send_message(chat_id, f'Отлично! Переходи по официальной ссылке и заполняй анкету (займет 5 минут):\n\n👉 {PARTNER_LINK}\n\nПосле заполнения напиши мне "Готово", я подскажу следующие шаги!')
                            send_message(chat_id, '⚠️ Важно: регистрируйся только по этой ссылке, чтобы я мог тебя сопровождать и помогать на всех этапах.')
                        
                        # 3. Доход и Оплата
                        elif any(word in text for word in ['сколько', 'зарплат', 'платят', 'доход', 'деньги', 'оплат', 'заработа', 'ставка', 'тариф', 'оклад']):
                            send_message(chat_id, 'Потенциальный доход зависит от города, времени и твоей активности (количества выполненных заказов).\n\nТочные цифры можно посчитать в калькуляторе на сайте регистрации. Ограничений по максимуму нет — чем больше заказов, тем выше выплата. 💰\n\nТакже есть доплаты в часы высокого спроса (Карта спроса).\n\nЧтобы начать зарабатывать, заполни анкету: ' + PARTNER_LINK)
                        
                        # 4. График, Время и Слоты
                        elif any(word in text for word in ['график', 'время', 'слот', 'работать', 'совмещ', 'учеб', 'студент', 'выходные', 'смена']):
                            send_message(chat_id, 'График полностью свободный! 🗓\nТы сам выбираешь, когда и сколько выходить на доставки. Можно совмещать с учебой или основной работой, выходить хоть на 2 часа в день.\n\nНачать можно тут: ' + PARTNER_LINK)
                        
                        # 5. Документы и Оформление
                        elif any(word in text for word in ['документ', 'паспорт', 'оформлен', 'регистрац', 'медкнижк', 'медицинск', 'инн', 'снилс']):
                            send_message(chat_id, 'Оформление проходит онлайн в приложении Яндекс Про. Обычно нужен паспорт с пропиской и ИНН. Если есть медкнижка — отлично, если нет — подскажу, как сделать.\n\nДля начала просто зарегистрируйся по ссылке: ' + PARTNER_LINK)
                        
                        # 6. Самозанятость и Налоги
                        elif any(word in text for word in ['самозанят', 'налог', 'ндфл', 'ип', 'ооо', 'юрлицо', 'гпх', 'договор']):
                            send_message(chat_id, 'Можно оформиться как самозанятый (налог всего 4-6%, выплаты на карту) или по договору ГПХ. Налоги удерживаются автоматически. Если ты самозанятый, нужно будет подключить приложение "Мой налог".\n\nНачать оформление: ' + PARTNER_LINK)
                        
                        # 7. Иностранные граждане
                        elif any(word in text for word in ['гражданств', 'иностранец', 'еаэс', 'украин', 'беларус', 'армян', 'казах', 'киргиз', 'патент', 'внж', 'рвп', 'миграцион']):
                            send_message(chat_id, 'Мы работаем с гражданами РФ, ЕАЭС (Беларусь, Армения, Казахстан, Киргизия) и другими гражданами при наличии необходимых документов (патент, ВНЖ, РВП). Точный список документов зависит от твоего статуса и города.\n\nЗаполни анкету, и система подскажет, что нужно именно тебе: ' + PARTNER_LINK)
                        
                        # 8. Транспорт (пеший/авто/вело)
                        elif any(word in text for word in ['пешком', 'велосипед', 'машин', 'авто', 'транспорт', 'самокат', 'права']):
                            send_message(chat_id, 'Можно доставлять пешком, на велосипеде или на автомобиле — как тебе удобнее! 🚶‍♂️🚲🚗\nДля автокурьеров есть доплаты за километраж. Если нет своего транспорта, в некоторых городах доступна аренда велосипедов или самокатов.\n\nРегистрируйся и выбирай удобный способ: ' + PARTNER_LINK)
                        
                        # 9. Страхи, Опыт и Возражения
                        elif any(word in text for word in ['боюсь', 'сложно', 'не умею', 'опыт', 'страшно', 'штраф', 'обман', 'кидалов', 'блокиров']):
                            send_message(chat_id, 'Не переживай! Опыт работы не требуется. В приложении Яндекс Про есть подробное обучение и поддержка на каждом шаге. Штрафов за разовые опоздания нет, главное — соблюдать правила сервиса. А я помогу тебе сориентироваться на старте. 🤝\n\nПопробовать свои силы можно тут: ' + PARTNER_LINK)
                        
                        # 10. Подтверждение регистрации ("Готово")
                        elif any(word in text for word in ['готово', 'сделал', 'зарегистр', 'заполнил', 'отправил']):
                            send_message(chat_id, 'Красавчик! 🚀 Скоро я проверю твою заявку в системе. А пока скажи, планируешь выходить пешком, на велосипеде или на машине?')
                        
                        # 11. Проверка на спам, брань или непонятный ввод
                        elif len(text) < 3:
                            send_message(chat_id, 'Пожалуйста, напиши чуть подробнее, чтобы я понял твой вопрос. 👀')
                        
                        # 12. Если бот не понял вопрос (ловушка на всё остальное)
                        else:
                            send_message(chat_id, 'Я пока не знаю ответа на этот вопрос 🤔\n\nПопробуй спросить иначе, или напиши /link, чтобы сразу получить ссылку на регистрацию. Либо задай вопрос мне напрямую, и я (человек) отвечу тебе чуть позже!')
                            
                        # ------------------------
                        
            time.sleep(1)
        except Exception as e:
            print(f"Ошибка: {e}")
            time.sleep(5)

if __name__ == '__main__':
    main()
